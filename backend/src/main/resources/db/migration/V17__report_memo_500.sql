-- 신고 메모 상한을 200자에서 500자로 늘립니다 (S15P21D205-1005).
--
-- 관리 화면에서 메모를 보기 시작하면서(972) 200자가 짧다는 판단이 나왔습니다. 피드백
-- 메시지(user_feedback.message)와 같은 500자로 맞춥니다.
--
-- VARCHAR 는 가변 길이라 이 변경으로 기존 행의 저장 공간은 바뀌지 않고, 새 행도 실제
-- 글자 수만큼만 차지합니다. 이 컬럼에는 인덱스도 정렬도 없어 최대 폭이 비용이 되는 자리가
-- 없습니다. 200 → 500 은 같은 VARCHAR 안에서 늘리는 것이라 InnoDB 가 테이블을 다시 쓰지
-- 않습니다(길이 표시가 1바이트에서 2바이트로 바뀌는 255바이트 경계는 utf8mb4 에서 이미
-- 넘어 있었습니다).
--
-- 서버 검증(SendReportRequest 의 @Size)과 엔티티 length 를 함께 500 으로 바꿔야 합니다.
-- 엔티티가 200 으로 남으면 ddl-auto=validate 가 기동을 막습니다.

ALTER TABLE user_reports
    MODIFY COLUMN memo VARCHAR(500) NULL;
